#include <stdio.h>
#include <string.h>
#include "OCR.h"
#include "ocr/OCRInternal.h"
#define CHECK(x) do { if (!(x)) { fprintf(stderr,"FAIL %d: %s\n",__LINE__,#x); return 1; } } while (0)
int main(void) {
    char text[256]="old result";
    static uint8_t pixels[CAMERA_FRAME_BYTES];
    CameraFrame frame={pixels,sizeof pixels,320,240};
    CHECK(ocr_read_text(text,sizeof text)==APP_NOT_READY && text[0]==0);
    CHECK(ocr_init()==APP_OK);
    CHECK(ocr_read_frame(NULL,text,sizeof text)==APP_ERROR && text[0]==0);
    CHECK(ocr_read_frame(&frame,NULL,10)==APP_ERROR);
    CHECK(ocr_read_frame(&frame,text,0)==APP_ERROR);
    CHECK(ocr_read_text(text,sizeof text)==APP_NOT_READY);
    CHECK(ocr_read_frame(&frame,text,sizeof text)==APP_NOT_READY && !text[0]);
    memset(pixels,255,sizeof pixels);
    CHECK(ocr_read_frame(&frame,text,sizeof text)==APP_NOT_READY && !text[0]);
    frame.length--; CHECK(ocr_read_frame(&frame,text,sizeof text)==APP_ERROR); frame.length++;
    OCRConfig config={.rotation=4}; CHECK(ocr_configure(&config)==APP_ERROR);
    config=(OCRConfig){.width=10}; CHECK(ocr_configure(&config)==APP_ERROR);
    config=(OCRConfig){.x=319,.width=10,.height=10}; CHECK(ocr_configure(&config)==APP_OK);
    CHECK(ocr_read_frame(&frame,text,sizeof text)==APP_ERROR && !text[0]);
    config=(OCRConfig){.rotation=1}; CHECK(ocr_configure(&config)==APP_OK);
    CHECK(ocr_read_frame(&frame,text,sizeof text)==APP_NOT_READY);
    CHECK(ocr_get_diagnostics(NULL)==APP_ERROR);
    FILE *line=fopen("line.bin","rb");
    if (line) {
        CHECK(fread(pixels,1,sizeof pixels,line)==sizeof pixels); fclose(line);
        config=(OCRConfig){0}; CHECK(ocr_configure(&config)==APP_OK);
        CHECK(ocr_read_frame(&frame,text,sizeof text)==APP_OK);
        CHECK(strcmp(text,"WATER")==0);
        text[0]='x'; CHECK(ocr_read_frame(&frame,text,1)==APP_ERROR && text[0]==0);
        CHECK(ocr_read_frame(&frame,text,5)==APP_ERROR && text[0]==0);
        CHECK(ocr_read_frame(&frame,text,6)==APP_OK && strcmp(text,"WATER")==0);
    }
    // Optional real handwritten normalized test vectors generated by training.
    FILE *vectors=fopen("vectors.bin","rb");
    if (vectors) {
        unsigned total=0,accepted=0,correct=0;
        uint8_t glyph[OCR_INPUT],expected,confidence;
        const char *alphabet="0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ";
        while (fread(&expected,1,1,vectors)==1) {
            CHECK(fread(glyph,1,OCR_INPUT,vectors)==OCR_INPUT);
            char predicted=ocr_classify_glyph(glyph,&confidence);
            if (predicted!='?') { ++accepted; correct+=predicted==alphabet[expected]; }
            ++total;
        }
        fclose(vectors);
        CHECK(total==1024 && accepted>400 && correct*100>=accepted*85);
        printf("Real held-out handwriting: %u/%u accepted, %u correct.\n",accepted,total,correct);
    }
    puts("PASS OCR boundaries: no frame, NULL, blank/dark input, malformed frame, ROI and rotation.");
    return 0;
}
